"""Generate a metro-area SVG (sub-region background + shared equirectangular
projection) for a capital metro, from Natural Earth admin-1. Generalized from
_gen_paris_metro_svg.py. Usage: python _gen_metro_svg.py <slug>  (london|rome|...)

For metros where NE admin-1 already has sub-region granularity:
  - France  -> departements   (Paris: region "Île-de-France")
  - UK      -> districts       (London: region "Greater London")
  - Italy   -> provinces       (Rome:   region "Lazio")
Berlin/Vienna/Budapest/Madrid are single admin-1 polygons -> need admin-2
(district) GeoJSON, handled separately.
"""
import json, io, sys, math, re

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace", write_through=True)
GEO = r"C:/Users/User/ne_admin1_10m.geojson"
OUTDIR = r"C:/Users/User/plizio-repo/lib/visualLab/maps/"

CONFIGS = {
    "london": {
        "admin": "United Kingdom", "region": "Greater London",
        "idPrefix": "GB", "var": "londonMetro", "proj": "projectCoordsLondon",
        "comment": "Greater London boroughs",
    },
    "rome": {
        "admin": "Italy", "region": "Lazio",
        "idPrefix": "IT", "var": "romeMetro", "proj": "projectCoordsRome",
        "comment": "Rome metro (Lazio provinces)",
    },
}

def norm(s):
    s = (s or "").lower().replace("’", "'").replace("'", "")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")

def coords_iter(geom):
    t = geom["type"]; cs = geom["coordinates"]
    if t == "Polygon":
        for ring in cs: yield ring
    elif t == "MultiPolygon":
        for poly in cs:
            for ring in poly: yield ring

def gen(slug):
    c = CONFIGS[slug]
    out = OUTDIR + c["var"] + ".svg.ts"
    d = json.load(open(GEO, encoding="utf-8"))
    feats = {}; names_by_key = {}
    for f in d["features"]:
        pr = f.get("properties", {})
        if pr.get("admin") != c["admin"] or pr.get("region") != c["region"]:
            continue
        en = pr.get("name_en") or pr.get("name") or ""
        key = norm(en)
        if not key: continue
        feats[key] = f["geometry"]
        names_by_key[key] = {"de": en, "hu": en, "ro": en, "en": en}
    print(f"{slug}: matched {len(feats)} sub-regions:", sorted(feats.keys()))
    if not feats:
        print("  NO MATCH — check admin/region names"); return

    minLon = minLat = 1e9; maxLon = maxLat = -1e9
    for g in feats.values():
        for ring in coords_iter(g):
            for lon, lat in ring:
                minLon = min(minLon, lon); maxLon = max(maxLon, lon)
                minLat = min(minLat, lat); maxLat = max(maxLat, lat)
    padLon = (maxLon - minLon) * 0.04; padLat = (maxLat - minLat) * 0.04
    minLon -= padLon; maxLon += padLon; minLat -= padLat; maxLat += padLat
    midLat = (minLat + maxLat) / 2
    cosLat = math.cos(math.radians(midLat))
    W = 1000.0
    S = W / ((maxLon - minLon) * cosLat)
    H = round((maxLat - minLat) * S, 2)

    def px(lon, lat):
        return [round((lon - minLon) * S * cosLat, 2), round((maxLat - lat) * S, 2)]
    def ring_to_path(ring):
        pts = [px(lon, lat) for lon, lat in ring]
        if not pts: return ""
        return "M" + "L".join(f"{x},{y}" for x, y in pts) + "Z"
    def geom_to_path(geom):
        return "".join(ring_to_path(r) for r in coords_iter(geom))

    regions = []
    for key, names in names_by_key.items():
        g = feats.get(key)
        if not g: continue
        path = geom_to_path(g)
        xs = []; ys = []
        for ring in coords_iter(g):
            for lon, lat in ring:
                p = px(lon, lat); xs.append(p[0]); ys.append(p[1])
        lx = round(sum(xs) / len(xs), 1); ly = round(sum(ys) / len(ys), 1)
        regions.append({"id": c["idPrefix"] + "-" + key, "name": names, "labelX": lx, "labelY": ly, "path": path})

    L = []
    L.append("// AUTO-GENERATED by scripts/_gen_metro_svg.py. Do not edit by hand.")
    L.append(f"// {c['comment']}, shared equirectangular projection.")
    L.append(f'export const {c["var"]}ViewBox = "0 0 1000 {H}";')
    L.append(f"export const {c['var'].upper()}_PROJECTION = {{")
    L.append(f"  minLon: {minLon:.6f}, maxLon: {maxLon:.6f}, minLat: {minLat:.6f}, maxLat: {maxLat:.6f},")
    L.append(f"  S: {S:.6f}, cosLat: {cosLat:.6f},")
    L.append("};")
    L.append(f"export function {c['proj']}(lon: number, lat: number): [number, number] {{")
    L.append(f"  const p = {c['var'].upper()}_PROJECTION;")
    L.append("  const x = (lon - p.minLon) * p.S * p.cosLat;")
    L.append("  const y = (p.maxLat - lat) * p.S;")
    L.append("  return [Math.round(x * 100) / 100, Math.round(y * 100) / 100];")
    L.append("}")
    L.append("export interface RegionPath { id: string; name: { de: string; hu: string; ro: string; en: string }; capital: string; labelX: number; labelY: number; path: string; }")
    L.append(f"export const {c['var']}Map: RegionPath[] = [")
    for r in regions:
        nm = json.dumps(r["name"], ensure_ascii=False)
        L.append(f'  {{ id: "{r["id"]}", name: {nm}, capital: "", labelX: {r["labelX"]}, labelY: {r["labelY"]}, path: "{r["path"]}" }},')
    L.append("];")
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print(f"  -> {out} | viewBox 0 0 1000 {H} | regions {len(regions)}")

if __name__ == "__main__":
    targets = sys.argv[1:] or list(CONFIGS.keys())
    for t in targets:
        if t in CONFIGS: gen(t)
        else: print("unknown:", t)
