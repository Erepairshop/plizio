#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repo = process.cwd();
const catalogDir = path.join(repo, "lib", "seo", "poi-html-ui", "catalogs");
const output = path.join(repo, "lib", "seo", "poi-html-ui.generated.ts");
const placeholderPattern = /\{[A-Za-z][A-Za-z0-9_]*\}/g;

function placeholders(value) {
  return [...String(value).matchAll(placeholderPattern)].map((match) => match[0]).sort();
}

const files = fs.readdirSync(catalogDir).filter((name) => /^[a-z]{2}(?:-[a-z]{2})?\.json$/i.test(name)).sort();
if (!files.includes("en.json")) throw new Error("Missing source catalog: en.json");
const catalogs = {};
for (const file of files) {
  const parsed = JSON.parse(fs.readFileSync(path.join(catalogDir, file), "utf8"));
  const lang = file.replace(/\.json$/i, "").toLowerCase();
  if (!parsed.strings || typeof parsed.strings !== "object" || Array.isArray(parsed.strings)) {
    throw new Error(`${file}: strings must be an object`);
  }
  catalogs[lang] = parsed.strings;
}

const source = catalogs.en;
for (const [lang, strings] of Object.entries(catalogs)) {
  if (lang === "en") continue;
  const missing = Object.keys(source).filter((key) => !(key in strings));
  const extra = Object.keys(strings).filter((key) => !(key in source));
  if (missing.length || extra.length) {
    throw new Error(`${lang}: catalog key mismatch; missing=${missing.length}, extra=${extra.length}`);
  }
  for (const key of Object.keys(source)) {
    const expected = placeholders(source[key]);
    const actual = placeholders(strings[key]);
    if (JSON.stringify(expected) !== JSON.stringify(actual)) {
      throw new Error(`${lang}:${key}: placeholder mismatch (${expected.join(",")} != ${actual.join(",")})`);
    }
  }
}

const banner = "// Generated by scripts/native-rollout/build-poi-html-ui-module.mjs. Do not edit manually.\n";
const body = `export const POI_HTML_UI_CATALOGS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(catalogs, null, 2)};\n`;
fs.writeFileSync(output, banner + body, "utf8");
console.log(JSON.stringify({ languages: Object.keys(catalogs), keys: Object.keys(source).length, output }));
