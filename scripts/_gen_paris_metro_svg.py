"""Generate lib/visualLab/maps/parisMetro.svg.ts — Île-de-France (Paris metro)
department-level SVG in a SHARED equirectangular projection (cos-lat corrected)
so POI markers projected with projectCoordsParis() overlay the dept paths exactly.
Source: C:/Users/User/ne_admin1_10m.geojson (France @ departement level)."""
import json, io, sys, math, re
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace", write_through=True)

GEO = r"C:/Users/User/ne_admin1_10m.geojson"
OUT = r"C:/Users/User/plizio-repo/lib/visualLab/maps/parisMetro.svg.ts"

# 8 IDF departments + localized names
IDF = {
    "paris":             {"de": "Paris", "hu": "Párizs", "ro": "Paris", "en": "Paris"},
    "seine-et-marne":    {"de": "Seine-et-Marne", "hu": "Seine-et-Marne", "ro": "Seine-et-Marne", "en": "Seine-et-Marne"},
    "yvelines":          {"de": "Yvelines", "hu": "Yvelines", "ro": "Yvelines", "en": "Yvelines"},
    "essonne":           {"de": "Essonne", "hu": "Essonne", "ro": "Essonne", "en": "Essonne"},
    "hauts-de-seine":    {"de": "Hauts-de-Seine", "hu": "Hauts-de-Seine", "ro": "Hauts-de-Seine", "en": "Hauts-de-Seine"},
    "seine-saint-denis": {"de": "Seine-Saint-Denis", "hu": "Seine-Saint-Denis", "ro": "Seine-Saint-Denis", "en": "Seine-Saint-Denis"},
    "val-de-marne":      {"de": "Val-de-Marne", "hu": "Val-de-Marne", "ro": "Val-de-Marne", "en": "Val-de-Marne"},
    "val-doise":         {"de": "Val-d'Oise", "hu": "Val-d'Oise", "ro": "Val-d'Oise", "en": "Val-d'Oise"},
}

def norm(s):
    s = (s or "").lower().replace("’", "'").replace("'", "")
    return re.sub(r"[^a-z]+", "-", s).strip("-")

d = json.load(open(GEO, encoding="utf-8"))
feats = {}; names_by_key = {}
for f in d["features"]:
    pr = f.get("properties", {})
    if pr.get("admin") != "France" or pr.get("region") != "Île-de-France":
        continue
    # name field has typos (e.g. "Seien-et-Marne") → prefer name_en
    en = pr.get("name_en") or pr.get("name") or ""
    key = norm(en)
    feats[key] = f["geometry"]
    names_by_key[key] = IDF.get(key) or {"de": en, "hu": en, "ro": en, "en": en}
print("matched IDF depts (region=Île-de-France):", sorted(feats.keys()))
IDF = names_by_key  # drive emission off what we actually matched

# --- bbox over all IDF geometry ---
def coords_iter(geom):
    t = geom["type"]; cs = geom["coordinates"]
    if t == "Polygon":
        for ring in cs: yield ring
    elif t == "MultiPolygon":
        for poly in cs:
            for ring in poly: yield ring

minLon = minLat = 1e9; maxLon = maxLat = -1e9
for g in feats.values():
    for ring in coords_iter(g):
        for lon, lat in ring:
            minLon = min(minLon, lon); maxLon = max(maxLon, lon)
            minLat = min(minLat, lat); maxLat = max(maxLat, lat)
# pad 4%
padLon = (maxLon - minLon) * 0.04; padLat = (maxLat - minLat) * 0.04
minLon -= padLon; maxLon += padLon; minLat -= padLat; maxLat += padLat
midLat = (minLat + maxLat) / 2
cosLat = math.cos(math.radians(midLat))

# fit width to 1000, height keeps true aspect (no horizontal stretch)
W = 1000.0
S = W / ((maxLon - minLon) * cosLat)        # pixels per degree-lat
H = round((maxLat - minLat) * S, 2)

def px(lon, lat):
    return [round((lon - minLon) * S * cosLat, 2), round((maxLat - lat) * S, 2)]

def ring_to_path(ring):
    pts = [px(lon, lat) for lon, lat in ring]
    if not pts: return ""
    seg = "M" + "L".join(f"{x},{y}" for x, y in pts) + "Z"
    return seg

def geom_to_path(geom):
    return "".join(ring_to_path(r) for r in coords_iter(geom))

regions = []
for key, names in IDF.items():
    g = feats.get(key)
    if not g: continue
    path = geom_to_path(g)
    # label = projected centroid of bbox of this dept
    xs = []; ys = []
    for ring in coords_iter(g):
        for lon, lat in ring:
            p = px(lon, lat); xs.append(p[0]); ys.append(p[1])
    lx = round(sum(xs) / len(xs), 1); ly = round(sum(ys) / len(ys), 1)
    regions.append({"id": "FR-" + key, "name": names, "labelX": lx, "labelY": ly, "path": path})

# --- emit TS ---
lines = []
lines.append("// AUTO-GENERATED by scripts/_gen_paris_metro_svg.py. Do not edit by hand.")
lines.append("// Île-de-France (Paris metro) departments, shared equirectangular projection.")
lines.append(f'export const parisMetroViewBox = "0 0 1000 {H}";')
lines.append("export const PARIS_METRO_PROJECTION = {")
lines.append(f"  minLon: {minLon:.6f}, maxLon: {maxLon:.6f}, minLat: {minLat:.6f}, maxLat: {maxLat:.6f},")
lines.append(f"  S: {S:.6f}, cosLat: {cosLat:.6f},")
lines.append("};")
lines.append("export function projectCoordsParis(lon: number, lat: number): [number, number] {")
lines.append("  const p = PARIS_METRO_PROJECTION;")
lines.append("  const x = (lon - p.minLon) * p.S * p.cosLat;")
lines.append("  const y = (p.maxLat - lat) * p.S;")
lines.append("  return [Math.round(x * 100) / 100, Math.round(y * 100) / 100];")
lines.append("}")
lines.append("export interface RegionPath { id: string; name: { de: string; hu: string; ro: string; en: string }; capital: string; labelX: number; labelY: number; path: string; }")
lines.append("export const parisMetroMap: RegionPath[] = [")
for r in regions:
    nm = json.dumps(r["name"], ensure_ascii=False)
    lines.append(f'  {{ id: {json.dumps(r["id"])}, name: {nm}, capital: "", labelX: {r["labelX"]}, labelY: {r["labelY"]}, path: {json.dumps(r["path"])} }},')
lines.append("];")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(f"viewBox: 0 0 1000 {H} | regions: {len(regions)} | bytes: {len(open(OUT,encoding='utf-8').read())}")
