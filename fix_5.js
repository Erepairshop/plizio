for (const f of files) {
  if (!fs.existsSync(f)) continue;
  let content = fs.readFileSync(f, 'utf8');

  // Fix Colombia multiple keys or missing closing object brace at EOF
  content = content.replace(/(\s*en:\s*\[[\s\S]*?\]\s*\})\s*,\s*\n\];/g, '$1\n  }\n];');
  content = content.replace(/(\s*en:\s*\[[\s\S]*?\]\s*\})\s*,\s*\n\s*\n\];/g, '$1\n  }\n];');

  // Also fix Colombia missing `{` for POI object if we accidentally replaced something.
  // Wait, let's fix the missing object end anywhere it says `  ,` instead of `  },`
  content = content.replace(/\n\s*,\n\s*(descriptionAdvanced|factsAdvanced):/g, '\n  },\n    $1:');

  // Fix Uruguay invalid character before `de: [`
  content = content.replace(/en:\s*\[\s*\]\s*,\s*\n\s*[^\w\s]+\s*\n\s*de:\s*\[/g, 'en: []\n    },\n    facts: {\n      de: [');

  // Sometimes there is an empty `en: [],` then `facts:`
  content = content.replace(/en:\s*\[\s*\]\s*,\s*\n\s*de:\s*\[/g, 'en: []\n    },\n    facts: {\n      de: [');

  // Fix `descriptionAdvanced: { ... }, factsAdvanced: { ... }, \n { id: ...`
  // This means the POI object is not closed.
  content = content.replace(/(\s*en:\s*\[[\s\S]*?\]\s*\})\s*,\s*\n\s*\{\s*\n\s*id:/g, '$1\n  },\n  {\n    id:');

  fs.writeFileSync(f, content);
}

